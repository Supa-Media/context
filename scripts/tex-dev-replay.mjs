#!/usr/bin/env node
// Writes apps/mcp/src/texDev/replay.generated.js: the Tex Architecture Lab's own Replay code
// (apps/mobile/features/tex/lab/engine/replayEntry.ts: the moments, each turn's measured times, what every step got
// and gave, the prompt at a version, a job's runs, the notes a turn read, the Lab's address), bundled to plain
// JavaScript so the gateway, which imports only relative JS, answers `tex_dev` with what the Lab shows
// (apps/mcp/src/texDev/replay.js). One Replay, never a copy.
//
//   node scripts/tex-dev-replay.mjs           write the file
//   node scripts/tex-dev-replay.mjs --check   exit 1 if the file on disk is stale
//
// CI runs --check (ci.yml, beside the canvas's), so a change to the Lab's Replay that is not followed by this script
// fails the build. The header names the esbuild that built it, so a failure after a lockfile bump says so.

import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const ENTRY = path.join(ROOT, "apps/mobile/features/tex/lab/engine/replayEntry.ts");
const OUT = path.join(ROOT, "apps/mcp/src/texDev/replay.generated.js");
// esbuild is a root transitive dependency, reached from the repo root as the other bundle scripts reach it.
const require = createRequire(path.join(ROOT, "package.json"));
const esbuild = require("esbuild");

export async function buildReplay() {
  const result = await esbuild.build({
    entryPoints: [ENTRY],
    absWorkingDir: ROOT,
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    write: false,
    legalComments: "none",
    // Minified: a bundle, read by nobody, kept under the file-size rule without a generated-file exception.
    minify: true,
    // Strings as "\n" escapes, never template literals with real line breaks, so the bundle stays a few lines.
    supported: { "template-literal": false },
    logLevel: "error",
  });
  const body = result.outputFiles[0].text;
  const header = `// GENERATED by scripts/tex-dev-replay.mjs from apps/mobile/features/tex/lab/engine/replayEntry.ts\n// (the Lab's own Replay). Do not edit: run \`node scripts/tex-dev-replay.mjs\`.\n// Built with esbuild ${esbuild.version}.\n`;
  return header + body;
}

const wanted = await buildReplay();
if (process.argv.includes("--check")) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (have !== wanted) {
    console.error("apps/mcp/src/texDev/replay.generated.js is not what the Lab's Replay builds.");
    console.error("Run `node scripts/tex-dev-replay.mjs` (built on install, never committed).");
    process.exit(1);
  }
  console.log("tex-dev replay: up to date");
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, wanted);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${wanted.length} bytes)`);
}
