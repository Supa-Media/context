/**
 * THE DRAWING IN EVERY TEX AGENT'S PROMPT (Dev2, 2026-11-06: "make sure the
 * architecture in code is loaded into every agents context, and tell them what
 * part of the graph they are").
 *
 * `docs/architecture/tex.md` is the one drawing of Tex. This turns its three
 * drawn sections into `apps/mcp/src/agent/texArchitecture.generated.js`, which
 * `texArchitecture.js` puts at the head of each agent's prompt. The colours
 * and the HTML line breaks are dropped; every box and arrow stays.
 *
 *   node scripts/tex-architecture-module.mjs           write the module
 *   node scripts/tex-architecture-module.mjs --check   fail when it is stale
 *
 * `tex-diagram-check.mjs` runs the check in CI, so a redrawn page that was not
 * regenerated fails there.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const PAGE = "docs/architecture/tex.md";
export const MODULE = "apps/mcp/src/agent/texArchitecture.generated.js";

/** The drawn sections of the page, without colours, comments or HTML line breaks. */
export function mapOf(page) {
  const start = page.indexOf("## 1. ");
  const end = page.indexOf("## The rule");
  if (start === -1 || end === -1 || end < start) throw new Error(`${PAGE}: sections 1 to 3 and "## The rule" not found`);
  return page
    .slice(start, end)
    .replace(/^\s*classDef .*\n/gm, "")
    .replace(/:::\w+/g, "")
    .replace(/<!--.*?-->\n/g, "")
    .replaceAll("<br/>", "; ")
    .trim();
}

/** The module's source for a page. */
export function moduleFor(page) {
  return [
    `// Generated by scripts/tex-architecture-module.mjs from ${PAGE}. Do not edit: redraw the page and run the script.`,
    "",
    "/** Tex's drawing, sections 1 to 3, as every Tex agent reads it (`texArchitecture.js`). */",
    `export const TEX_MAP = ${JSON.stringify(mapOf(page))};`,
    "",
  ].join("\n");
}

/** Whether the committed module is what the page makes. */
export function moduleIsCurrent(root = ROOT) {
  return readFileSync(join(root, MODULE), "utf8") === moduleFor(readFileSync(join(root, PAGE), "utf8"));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    if (!moduleIsCurrent()) {
      console.error(`tex-architecture-module: ${MODULE} is not what ${PAGE} makes: run node scripts/tex-architecture-module.mjs`);
      process.exit(1);
    }
    console.log("tex-architecture-module: current");
  } else {
    writeFileSync(join(ROOT, MODULE), moduleFor(readFileSync(join(ROOT, PAGE), "utf8")));
    console.log(`tex-architecture-module: wrote ${MODULE}`);
  }
}
