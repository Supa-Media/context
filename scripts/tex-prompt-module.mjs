/**
 * TEX'S PROMPT WORDS, IN THE REPOSITORY (Dev2, 2026-11-14: the words live "in the repo, beside the config", so the
 * Lab's config is the one source of what Tex is told).
 *
 * Each prompt module is one Markdown file, `packages/shared/src/texPrompt/<name>.md`, the words exactly as Tex is
 * given them. Which modules a turn gets, and in what order, is the config's (`texConfig.json`: the `p-<name>` entries
 * of the front door's and the background job's context). A Worker cannot read a Markdown file, so this writes the
 * files' words into `packages/shared/src/texPrompt.generated.json`, which the gateway and the Lab import.
 *
 *   node scripts/tex-prompt-module.mjs           write the module
 *   node scripts/tex-prompt-module.mjs --check   fail when it is stale
 *
 * `tex-diagram-check.mjs` runs the check in CI, and the gateway suite holds it too (`texConfig.test.mjs`).
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const FOLDER = "packages/shared/src/texPrompt";
export const MODULE = "packages/shared/src/texPrompt.generated.json";

const NAME = /^[a-z][a-z0-9-]{0,47}$/;

/** Every module's words, `{name: text}`, sorted by name; the text trimmed, as Tex is given it. */
export function wordsOf(root = ROOT) {
  const out = {};
  for (const file of readdirSync(join(root, FOLDER)).sort()) {
    if (!file.endsWith(".md")) continue;
    const name = file.slice(0, -3);
    if (!NAME.test(name)) throw new Error(`${FOLDER}/${file}: a module's name is lowercase letters, digits and hyphens`);
    const text = readFileSync(join(root, FOLDER, file), "utf8").replace(/^\uFEFF/, "").trim();
    if (text === "") throw new Error(`${FOLDER}/${file} is empty`);
    if (/^---\r?\n/.test(text)) throw new Error(`${FOLDER}/${file}: no front matter; the file is the words Tex is given`);
    out[name] = text;
  }
  return out;
}

/** The module's text for a set of words: JSON, so the gateway and the Lab import it as they import the config. */
export function moduleFor(words) {
  const about = `Generated by scripts/tex-prompt-module.mjs from ${FOLDER}/*.md. Do not edit: change a file there and run the script.`;
  return `${JSON.stringify({ about, modules: words }, null, 2)}\n`;
}

/** Whether the committed module is what the files make. */
export function moduleIsCurrent(root = ROOT) {
  return readFileSync(join(root, MODULE), "utf8") === moduleFor(wordsOf(root));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    if (!moduleIsCurrent()) {
      console.error(`tex-prompt-module: ${MODULE} is not what ${FOLDER}/*.md make: run node scripts/tex-prompt-module.mjs`);
      process.exit(1);
    }
    console.log("tex-prompt-module: current");
  } else {
    writeFileSync(join(ROOT, MODULE), moduleFor(wordsOf()));
    console.log(`tex-prompt-module: wrote ${MODULE}`);
  }
}
