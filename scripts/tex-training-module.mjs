/**
 * THE TRAINING SET, AS THE STEPS READ IT (Dev2, 2026-11-15: Training is "shown to steps as examples").
 *
 * Training conversations live in `apps/mcp/bench/sets/training/<id>.json` (the contract: `packages/shared/src/texSets.cjs`).
 * A Worker cannot read a folder, so this writes every Training label as a moment (the chat before, the message, the
 * label) into `packages/shared/src/texTraining.generated.json`, by node; `texTraining.cjs` turns a step's moments into
 * the module its context names (`train:<nodeId>`).
 *
 *   node scripts/tex-training-module.mjs           write the module
 *   node scripts/tex-training-module.mjs --check   fail when it is stale, or a conversation breaks the contract
 *
 * `tex-diagram-check.mjs` runs the check in CI, and the gateway suite holds it too (`texTraining.test.mjs`).
 */

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const FOLDER = "apps/mcp/bench/sets/training";
export const MODULE = "packages/shared/src/texTraining.generated.json";

/** Every Training conversation, in file-name order; throws on one that breaks the contract or sits in the wrong set. */
export function trainingConversations(root = ROOT) {
  const { check } = require(join(root, "packages/shared/src/texSets.cjs"));
  const { WHY } = require(join(root, "packages/shared/src/textDecide.cjs"));
  const config = JSON.parse(readFileSync(join(root, "packages/shared/src/texConfig.json"), "utf8"));
  const dir = join(root, FOLDER);
  if (!existsSync(dir)) return [];
  const out = [];
  for (const file of readdirSync(dir).sort()) {
    if (!file.endsWith(".json")) continue;
    const c = JSON.parse(readFileSync(join(dir, file), "utf8"));
    const problems = check(c, config, { why: Object.keys(WHY) });
    if (c.set !== "training") problems.push(`set is "${c.set}", but it is in the Training folder`);
    if (`${c.id}.json` !== file) problems.push(`its id "${c.id}" is not its file name`);
    if (problems.length > 0) throw new Error(`${FOLDER}/${file}: ${problems.join("; ")}`);
    out.push(c);
  }
  return out;
}

/** The module's text: every node's moments, nodes sorted by id. */
export function moduleFor(conversations, root = ROOT) {
  const { momentsOf } = require(join(root, "packages/shared/src/texTraining.cjs"));
  const moments = momentsOf(conversations);
  const nodes = Object.fromEntries(Object.keys(moments).sort().map((id) => [id, moments[id]]));
  const about = `Generated by scripts/tex-training-module.mjs from ${FOLDER}/*.json. Do not edit: change a conversation there (or on the Lab's Testing tab) and run the script.`;
  // One moment per line, so the module stays short however many Training labels there are (`pnpm architecture`), and
  // invisible and direction characters as escapes, as the sets' own files write them (`check-identifiers`).
  const one = (v) => JSON.stringify(v);
  const byNode = Object.entries(nodes).map(([id, list]) => `    ${one(id)}: [\n${list.map((m) => "      " + one(m)).join(",\n")}\n    ]`);
  const text = `{\n  "about": ${one(about)},\n  "nodes": {\n${byNode.join(",\n")}\n  }\n}\n`;
  return text.replace(/[\u200B-\u200F\u202A-\u202E\u2066-\u2069\uFEFF]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).toUpperCase().padStart(4, "0"));
}

/** Whether the committed module is what the conversations make. */
export function moduleIsCurrent(root = ROOT) {
  return existsSync(join(root, MODULE)) && readFileSync(join(root, MODULE), "utf8") === moduleFor(trainingConversations(root), root);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    if (!moduleIsCurrent()) {
      console.error(`tex-training-module: ${MODULE} is not what ${FOLDER}/*.json make: run node scripts/tex-training-module.mjs`);
      process.exit(1);
    }
    console.log("tex-training-module: current");
  } else {
    writeFileSync(join(ROOT, MODULE), moduleFor(trainingConversations()));
    console.log(`tex-training-module: wrote ${MODULE}`);
  }
}
