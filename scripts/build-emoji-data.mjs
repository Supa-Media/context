#!/usr/bin/env node
/**
 * Vendor the standard emoji table the editor's `:` menu searches.
 *
 *     node scripts/build-emoji-data.mjs
 *
 * The source is `gemoji` (MIT, wooorm/gemoji), GitHub's shortcode list: the
 * same names people already type in Slack and GitHub, which is the whole
 * point of `:tada:`. Vendored rather than depended on for the reason
 * `build-reserved-names.mjs` gives, plus one of its own: the table is packed
 * into one string so the native editor's inlined bundle carries tens of
 * kilobytes rather than the package's few hundred.
 *
 * Fetched from the npm registry tarball, pinned by version, and the generated
 * file records the tarball's SHA-256 so a re-run's diff is readable.
 */

import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync } from "node:zlib";

const VERSION = "8.1.0";
const TARBALL = `https://registry.npmjs.org/gemoji/-/gemoji-${VERSION}.tgz`;

const here = dirname(fileURLToPath(import.meta.url));
const out = join(resolve(here, ".."), "apps", "mobile", "features", "console", "files", "emoji", "standardEmoji.generated.ts");

/** One file out of a tar archive, by name. */
function untar(archive, wanted) {
  for (let offset = 0; offset + 512 <= archive.length; ) {
    const name = archive.subarray(offset, offset + 100).toString("utf8").replace(/\0.*$/s, "");
    if (name === "") break;
    const size = parseInt(archive.subarray(offset + 124, offset + 136).toString("utf8").replace(/\0.*$/s, "").trim(), 8);
    const body = archive.subarray(offset + 512, offset + 512 + size);
    if (name === wanted) return body.toString("utf8");
    offset += 512 + Math.ceil(size / 512) * 512;
  }
  throw new Error(`${wanted} is not in the tarball`);
}

const response = await fetch(TARBALL);
if (!response.ok) throw new Error(`${TARBALL} answered ${response.status}`);
const tarball = Buffer.from(await response.arrayBuffer());
const digest = createHash("sha256").update(tarball).digest("hex");
const source = untar(gunzipSync(tarball), "package/index.js");
const moduleUrl = `data:text/javascript;base64,${Buffer.from(source).toString("base64")}`;
const { gemoji } = await import(moduleUrl);

/**
 * The zero-width joiner inside a family or a flag, escaped: the repository
 * refuses invisible characters written literally (`check-no-identifiers.mjs`),
 * and `\u200d` in a string literal is the same character to the parser.
 */
const visible = (literal) =>
  literal.replace(/[\u00ad\u061c\u180e\u200b-\u200f\u202a-\u202e\u2060-\u2064\u2066-\u2069\ufeff\ufff9-\ufffb]/g, (char) =>
    `\\u${char.charCodeAt(0).toString(16).padStart(4, "0")}`,
  );

const clean = (text) => text.replace(/[\t\n]/g, " ").trim();
const rows = gemoji.map((entry) =>
  [entry.emoji, entry.names.map(clean).join(","), entry.tags.map(clean).join(" "), clean(entry.description)].join("\t"),
);

writeFileSync(
  out,
  `/* Generated by scripts/build-emoji-data.mjs from gemoji ${VERSION} (MIT). Do not edit. */
/* sha256 of ${TARBALL}: ${digest} */

/** One emoji per line: the character, its names, its tags, its description, tab-separated. */
export const STANDARD_EMOJI_TABLE = ${visible(JSON.stringify(rows.join("\n")))};
`,
);
console.log(`wrote ${rows.length} emoji to ${out}`);
