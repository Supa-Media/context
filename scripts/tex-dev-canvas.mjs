#!/usr/bin/env node
// Writes apps/mcp/src/texDev/canvas.generated.js: the Tex Architecture Lab's own canvas drawing
// (apps/mobile/features/tex/lab/views/canvas/render.ts, with snapshot.ts and the Lab's stylesheet),
// bundled to plain JavaScript so the gateway, which imports only relative JS, can draw the same picture
// the Lab does for `tex_dev snapshot` (apps/mcp/src/texDev/snapshot.js). One drawing, never a copy.
//
//   node scripts/tex-dev-canvas.mjs           write the file
//   node scripts/tex-dev-canvas.mjs --check   exit 1 if the file on disk is stale
//
// CI runs --check (fast-guards.yml), so a change to the Lab's drawing, its stylesheet, its groups or Tex's
// config that is not followed by this script fails the build. The header names the esbuild that built it,
// so a failure after a lockfile bump says so.

import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const ENTRY = path.join(ROOT, "apps/mobile/features/tex/lab/views/canvas/snapshot.ts");
const OUT = path.join(ROOT, "apps/mcp/src/texDev/canvas.generated.js");
// esbuild is a root transitive dependency, reached from the repo root as the other bundle scripts reach it.
const require = createRequire(path.join(ROOT, "package.json"));
const esbuild = require("esbuild");

export async function buildCanvas() {
  const result = await esbuild.build({
    entryPoints: [ENTRY],
    absWorkingDir: ROOT,
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    write: false,
    legalComments: "none",
    logLevel: "error",
  });
  const body = result.outputFiles[0].text;
  const header = `// GENERATED by scripts/tex-dev-canvas.mjs from apps/mobile/features/tex/lab/views/canvas/snapshot.ts\n// (the Lab's own canvas drawing). Do not edit: run \`node scripts/tex-dev-canvas.mjs\`.\n// Built with esbuild ${esbuild.version}.\n`;
  return header + body;
}

const wanted = await buildCanvas();
if (process.argv.includes("--check")) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (have !== wanted) {
    console.error("apps/mcp/src/texDev/canvas.generated.js is not what the Lab's canvas drawing builds.");
    console.error("Run `node scripts/tex-dev-canvas.mjs` and commit the result.");
    process.exit(1);
  }
  console.log("tex-dev canvas: up to date");
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, wanted);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${wanted.length} bytes)`);
}
