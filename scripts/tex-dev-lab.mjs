#!/usr/bin/env node
// Writes apps/mcp/src/texDev/lab.generated.js: what the Tex Architecture Lab computes in the browser
// (apps/mobile/features/tex/lab/engine/forMcp.ts: its simulation, its diff and run config, the bench cases and
// their fit, the modules and their word diff, its catalogues), bundled to plain JavaScript so the gateway, which
// imports only relative JS, answers `tex_dev` sim, compare, config, bench, modules and reference with the Lab's
// own functions (apps/mcp/src/texDev/lab.js). One computation, never a copy.
//
//   node scripts/tex-dev-lab.mjs           write the file
//   node scripts/tex-dev-lab.mjs --check   exit 1 if the file on disk is stale
//
// CI runs --check (ci.yml, beside tex-dev-canvas), so a change to the Lab's engine, its data, the bench cases or
// Tex's config that is not followed by this script fails the build. The header names the esbuild that built it,
// so a failure after a lockfile bump says so.

import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const ENTRY = path.join(ROOT, "apps/mobile/features/tex/lab/engine/forMcp.ts");
const OUT = path.join(ROOT, "apps/mcp/src/texDev/lab.generated.js");
// esbuild is a root transitive dependency, reached from the repo root as the other bundle scripts reach it.
const require = createRequire(path.join(ROOT, "package.json"));
const esbuild = require("esbuild");

export async function buildLab() {
  const result = await esbuild.build({
    entryPoints: [ENTRY],
    absWorkingDir: ROOT,
    bundle: true,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    write: false,
    legalComments: "none",
    // Minified: a bundle, read by nobody, kept under the file-size rule without a generated-file exception.
    minify: true,
    // Strings as "\n" escapes, never template literals with real line breaks, so the bundle stays a few lines.
    supported: { "template-literal": false },
    logLevel: "error",
  });
  const body = result.outputFiles[0].text;
  const header = `// GENERATED by scripts/tex-dev-lab.mjs from apps/mobile/features/tex/lab/engine/forMcp.ts\n// (what the Lab computes in the browser). Do not edit: run \`node scripts/tex-dev-lab.mjs\`.\n// Built with esbuild ${esbuild.version}.\n`;
  return header + body;
}

const wanted = await buildLab();
if (process.argv.includes("--check")) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (have !== wanted) {
    console.error("apps/mcp/src/texDev/lab.generated.js is not what the Lab's engine builds.");
    console.error("Run `node scripts/tex-dev-lab.mjs` and commit the result.");
    process.exit(1);
  }
  console.log("tex-dev lab: up to date");
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, wanted);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${wanted.length} bytes)`);
}
