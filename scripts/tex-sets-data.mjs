#!/usr/bin/env node
// Writes packages/shared/src/texSetsRepo.generated.json: Tex's Training and Dev conversations, read from
// apps/mcp/bench/sets (contract: packages/shared/src/texSets.cjs).
//
//   node scripts/tex-sets-data.mjs           write the file
//   node scripts/tex-sets-data.mjs --check   exit 1 if the file on disk is stale
//
// Refuses to write while the conversations have problems (see tex-sets-check.mjs). Node built-ins only.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT = path.join(ROOT, "packages/shared/src/texSetsRepo.generated.json");
const { loadSets, loadContract, problemsOf, jsonFile } = await import(
  pathToFileURL(path.join(ROOT, "apps/mcp/bench/sets.mjs")).href
);

let convs;
try {
  convs = await loadSets();
} catch (e) {
  console.error(e.message);
  process.exit(1);
}
const { config, why } = loadContract();
const problems = problemsOf(convs, { config, why });
if (problems.length) {
  for (const p of problems) console.error(p);
  console.error("Fix the conversations before generating the data file");
  process.exit(1);
}

// One conversation per line keeps the bundle under the size check's line limit as the sets grow.
const line = (v) => jsonFile(v).trim().replace(/\n\s*/g, "");
const content = `{"about":${JSON.stringify("GENERATED by scripts/tex-sets-data.mjs from apps/mcp/bench/sets; do not edit")},"sets":[\n${convs.map(line).join(",\n")}\n]}\n`;
const rel = path.relative(ROOT, OUT);

if (process.argv.includes("--check")) {
  const onDisk = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : null;
  if (onDisk !== content) {
    console.error(`${rel} is out of date with apps/mcp/bench/sets. Run: node scripts/tex-sets-data.mjs`);
    process.exit(1);
  }
  console.log(`${rel} is up to date (${convs.length} conversations)`);
} else {
  fs.writeFileSync(OUT, content);
  console.log(`wrote ${rel} (${convs.length} conversations)`);
}
